    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed

        int red = tblNarudzbenice.getSelectedRow();
        if (red < 0) {
            JOptionPane.showMessageDialog(this, "Izaberi narudžbenicu koju želiš da obrišeš.");
            return;
        }

        Narudzbenica n = narudzbenice.get(red);
        int izbor = JOptionPane.showConfirmDialog(this,
                "Da li sigurno želiš da obrišeš narudžbenicu " + n.getSifraNarudzbenice()
                + "? Stanje materijala će biti vraćeno.",
                "Potvrda brisanja", JOptionPane.YES_NO_OPTION);
        if (izbor != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            Odgovor o = komunikacija.posalji(new Zahtev("OBRISI_NARUDZBENICU", n.getSifraNarudzbenice()));
            if (o.isUspesno()) {
                JOptionPane.showMessageDialog(this, "Narudžbenica je obrisana.");
            } else {
                JOptionPane.showMessageDialog(this, "Greška: " + o.getPoruka());
            }
            ucitaj();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Greška u komunikaciji: " + e.getMessage());
        }

    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        int red = tblNarudzbenice.getSelectedRow();
        if (red < 0) {
            JOptionPane.showMessageDialog(this, "Izaberi narudžbenicu koju želiš da izmeniš.");
            return;
        }

        FrmNarudzbenica frm = new FrmNarudzbenica(komunikacija, narudzbenice.get(red));
        frm.addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                ucitaj();
            }
        });
        frm.setVisible(true);

    }//GEN-LAST:event_btnIzmeniActionPerformed


