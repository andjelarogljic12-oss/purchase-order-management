    private void ucitaj() {
        try {
            Odgovor o = komunikacija.posalji(new Zahtev("VRATI_NARUDZBENICE", null));
            if (!o.isUspesno()) {
                throw new Exception(o.getPoruka());
            }
            narudzbenice = (List<Narudzbenica>) o.getPodaci();

            SimpleDateFormat format = new SimpleDateFormat("dd.MM.yyyy");
            model.setRowCount(0);
            for (Narudzbenica n : narudzbenice) {
                model.addRow(new Object[]{n.getSifraNarudzbenice(), format.format(n.getDatum()),
                    n.getMusterija().getNazivFirme(), n.getUkupnaKolicina(),
                    n.getUkupnaCenaBezPdv(), n.getUkupnaCenaSaPdv()});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Greška pri učitavanju: " + e.getMessage());
        }
    }

